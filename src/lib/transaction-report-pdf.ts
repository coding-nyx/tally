import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { inMonth, settingsForMonth, type BudgetData } from "./budget.ts";

const PAGE_WIDTH = 612;
const PAGE_HEIGHT = 792;
const MARGIN = 42;

/** Creates a Tally-branded personal report. It is never represented as a bank statement. */
export async function createTransactionReportPdf(data: BudgetData, month: string): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const settings = settingsForMonth(data, month);
  const transactions = data.transactions
    .filter((transaction) => inMonth(transaction.date, month))
    .slice()
    .sort((a, b) => a.date.localeCompare(b.date) || a.createdAt - b.createdAt);
  const totals = transactions.reduce((acc, transaction) => {
    acc[transaction.kind] += transaction.amountCents;
    return acc;
  }, { income: 0, expense: 0 });
  const remaining = totals.income - totals.expense;
  const pages: ReturnType<typeof pdf.addPage>[] = [];
  const columns = [MARGIN, 94, 148, 228, 430];
  let y = PAGE_HEIGHT - MARGIN;
  let page: ReturnType<typeof pdf.addPage>;
  page = newPage();

  drawText("TALLY", 20, bold, rgb(0.12, 0.19, 0.24));
  drawText("PERSONAL TRANSACTION REPORT", 11, bold, rgb(0.12, 0.19, 0.24), 26);
  drawText(`${monthLabel(month)}  |  ${data.currency}  |  ${transactions.length} entries`, 10, regular, rgb(0.35, 0.4, 0.43), 20);
  y -= 4;
  y = sectionHeading("Monthly summary", y);
  const summaryLine = `Income ${money(totals.income)}     Spending ${money(totals.expense)}     Remaining ${money(remaining)}`;
  drawText(summaryLine, 10, regular, rgb(0.15, 0.2, 0.23), 17);
  drawText(`Savings goal: ${safeText(settings.goalName)} - target ${money(settings.goalTargetCents)}`, 9, regular, rgb(0.35, 0.4, 0.43), 15);

  const budgetRows = Object.entries(settings.categoryBudgets).sort(([a], [b]) => a.localeCompare(b));
  if (budgetRows.length) {
    y = sectionHeading("Category budgets", y);
    for (const [category, budget] of budgetRows) {
      if (y < MARGIN + 55) { nextPage(); }
      const spent = transactions.filter((tx) => tx.kind === "expense" && tx.category === category)
        .reduce((sum, tx) => sum + tx.amountCents, 0);
      drawText(`${safeText(category)}  |  ${money(spent)} spent of ${money(budget)}`, 9, regular, rgb(0.2, 0.25, 0.27), 14);
    }
  }

  y = sectionHeading("Transactions", y);
  drawTableHeader();
  for (const transaction of transactions) {
    const description = safeText(transaction.note || "-", 47);
    const rowParts = [
      transaction.date,
      transaction.kind === "income" ? "Income" : "Expense",
      safeText(transaction.category, 24),
      description,
      money(transaction.amountCents),
    ];
    const rowHeight = Math.max(17, Math.ceil(description.length / 46) * 13 + 4);
    if (y - rowHeight < MARGIN + 35) {
      nextPage();
      drawText("Transactions (continued)", 12, bold, rgb(0.12, 0.19, 0.24), 20);
      drawTableHeader();
    }
    rowParts.forEach((value, index) => drawAt(value, columns[index] ?? MARGIN, y, index === 4 ? 8 : 8.5, regular));
    y -= rowHeight;
    page.drawLine({ start: { x: MARGIN, y }, end: { x: PAGE_WIDTH - MARGIN, y }, thickness: 0.35, color: rgb(0.87, 0.89, 0.9) });
    y -= 3;
  }

  for (let index = 0; index < pages.length; index += 1) {
    const footer = `Generated by Tally for personal reference - not a bank-issued statement - ${index + 1} / ${pages.length}`;
    pages[index]!.drawText(footer, { x: MARGIN, y: 20, size: 7.5, font: regular, color: rgb(0.4, 0.43, 0.45) });
  }
  return pdf.save();

  function newPage() {
    const next = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
    pages.push(next);
    page = next;
    y = PAGE_HEIGHT - MARGIN;
    return next;
  }
  function drawText(text: string, size: number, font: typeof regular, color: ReturnType<typeof rgb>, gap = 0) {
    page.drawText(safeText(text), { x: MARGIN, y, size, font, color, maxWidth: PAGE_WIDTH - 2 * MARGIN });
    y -= size + gap;
  }
  function drawAt(text: string, x: number, rowY: number, size: number, font: typeof regular) {
    const next = columns.indexOf(x) + 1;
    const nextX = next > 0 ? (columns[next] ?? PAGE_WIDTH - MARGIN) : PAGE_WIDTH - MARGIN;
    page.drawText(safeText(text), { x, y: rowY, size, font, maxWidth: nextX - x - 5 });
  }
  function sectionHeading(text: string, rowY: number): number {
    y = rowY;
    if (y < MARGIN + 65) nextPage();
    page.drawText(safeText(text), { x: MARGIN, y, size: 11, font: bold, color: rgb(0.12, 0.19, 0.24) });
    return y - 19;
  }
  function drawTableHeader() {
    const headers = ["Date", "Type", "Category", "Description", "Amount"];
    headers.forEach((value, index) => drawAt(value, columns[index] ?? MARGIN, y, 8.5, bold));
    y -= 15;
    page.drawLine({ start: { x: MARGIN, y }, end: { x: PAGE_WIDTH - MARGIN, y }, thickness: 0.8, color: rgb(0.46, 0.54, 0.58) });
    y -= 12;
  }
  function nextPage() {
    newPage();
  }
  function money(minor: number): string {
    return `${data.currency} ${new Intl.NumberFormat("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(minor / 100)}`;
  }
}

function monthLabel(month: string): string {
  const date = new Date(`${month}-01T00:00:00Z`);
  return new Intl.DateTimeFormat("en-US", { month: "long", year: "numeric", timeZone: "UTC" }).format(date);
}

/** Standard PDF fonts are WinAnsi; replace unsupported glyphs visibly instead of failing export. */
function safeText(value: string, maxLength = 180): string {
  return value.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[^\x20-\x7e]/g, "?").slice(0, maxLength);
}
